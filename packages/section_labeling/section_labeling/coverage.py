"""The coverage report and the review list.

The coverage report: proof that every line of a law was read, and what was decided about it.

Recomputed from the extracted text itself (not from the splitter's own bookkeeping): every line of the
document must belong to exactly one piece, or be page furniture. A line in no piece, or in two, is a
failure. Each piece is then shown with its label (or "unlabeled") and whether an architect approved it.
Plain code; the report is generated, never hand-edited.

The review list: the labels a person must look at first. Every piece labeled not_for_checking (it is
never checked, so a rule wrongly put there could let a design pass that should fail), and every piece a
rule or definition already cites (if its label is wrong, a rule rests on a misread piece), and every label
with an open question for the architects. And, found by
plain code whatever the AI said, every piece labeled reference that uses requirement words ("shall not",
"must", "not less than"...): only rules become formulas, so a requirement filed as reference could be missed. A reviewer
records a doubt as an open question on the label for an architect to answer. (Approving labels, the same
way as rules, is deferred for now.)
"""

import json
import re
from collections import Counter
from pathlib import Path

from document_extraction.sections import piece_keys
from rule_format.labels import LABEL_KINDS
from rule_format.rulebook import TERM_SCHEMAS, load, rulebook_paths, rules_folder


def line_problems(rows: list[dict], header: dict, pieces: dict[str, dict]) -> list[str]:
    """Lines of the extracted text not owned by exactly one piece (furniture counts as owned), plus the
    splitter's own problems (sections in the table of contents that weren't found, or the reverse)."""
    owners = Counter(k for p in pieces.values() for k in piece_keys(p))
    owners.update(tuple(k) for k in header["furniture"])
    # A book only partly brought in (layout icc): the lines of the pages read that belong to parts not brought in,
    # each named (header "outside": [page, first, last, part]).
    owners.update((pg, n) for pg, a, b, _ in header.get("outside", []) for n in range(a, b + 1))
    lines = [(r["page"], r["line"]) for r in rows[1:]]
    in_text = set(lines)
    problems = [f"p.{p} line {n}: in no piece" for p, n in lines if owners[(p, n)] == 0]
    problems += [f"p.{p} line {n}: in {owners[(p, n)]} pieces" for p, n in lines if owners[(p, n)] > 1]
    problems += [f"p.{p} line {n}: a piece claims a line that isn't in the text" for p, n in owners if (p, n) not in in_text]
    return problems + list(header.get("problems", ["the sections file has no 'problems' list; re-run python -m document_extraction"]))


def report(rows: list[dict], header: dict, pieces: dict[str, dict], labels: dict) -> str:
    """The Markdown report for one document."""
    problems = line_problems(rows, header, pieces)
    counts = Counter(labels.get(i, {}).get("label", "unlabeled") for i in pieces)
    approved = sum(labels.get(i, {}).get("status") == "approved" for i in pieces)
    partial = "outside" in header
    outside = sum(b - a + 1 for _, a, b, _ in header.get("outside", []))
    out = [f"# Coverage: {header['file']}", "",
           "Generated by `python -m section_labeling coverage`. Never hand-edit.", "",
           f"- **Lines of text:** {len(rows) - 1} ({len(header['furniture'])} are page furniture: the repeated page "
           "title, running header and download footer)" if not partial else
           f"- **Lines of text on the pages read:** {len(rows) - 1} (pages {_pages(header)}): "
           f"{len(rows) - 1 - len(header['furniture']) - outside} in the pieces brought in, "
           f"{len(header['furniture'])} page furniture (the stamped number, running head, footer), {outside} in parts "
           f"of the book not brought in ({len({o[3] for o in header['outside']})} parts, each named in the sections file)",
           f"- **Pieces:** {len(pieces)}, cut at the law's own headings" + (
               " (the brought-in sections, and every definition they use)" if partial else ""),
           (f"- **Lines in no piece or in two, or sections missing from the table of contents:** {len(problems)}"
            if not partial else f"- **Lines in no piece or in two, or problems cutting the book:** {len(problems)}")
           + (" ✓" if not problems else " ✗"),
           f"- **Labels:** " + ", ".join(f"{k} {counts[k]}" for k in (*LABEL_KINDS, "unlabeled")),
           f"- **Approved by an architect:** {approved} of {len(pieces)} (approval is deferred for now)", ""]
    out += [f"- ✗ {p}" for p in problems[:50]] + ([""] if problems else [])
    out += ["| Piece | Title | Pages | Label | Status |", "|---|---|---|---|---|"]
    for pid, p in pieces.items():
        pages = sorted({pg for pg, _, _ in p["lines"]})
        where = str(pages[0]) if len(pages) == 1 else f"{pages[0]}–{pages[-1]}"
        entry = labels.get(pid, {})
        title = p["title"].replace("|", "/")
        out.append(f"| {pid} | {title} | {where} | {entry.get('label', 'unlabeled')} | {entry.get('status', '')} |")
    return "\n".join(out) + "\n"


def _pages(header: dict) -> str:
    """The pages read, as ranges: "34–56, 99–105"."""
    pages = sorted(int(p) for p in header.get("line_counts", {}))
    runs: list[list[int]] = []
    for p in pages:
        if runs and runs[-1][1] == p - 1:
            runs[-1][1] = p
        else:
            runs.append([p, p])
    return ", ".join(str(a) if a == b else f"{a}–{b}" for a, b in runs)


def cited_by(j: Path, file: str, pieces: dict[str, dict]) -> dict[str, list[str]]:
    """{piece id: [rule or definition ids citing it]}, from every source in every rulebook (5_zoning_rules)
    and the definitions and uses (4_term_definitions) that quotes this document. A rule drafted by the script
    (5_zoning_rules/drafted/) is listed as "drafted:<id>", so it isn't merged with a hand rule of the same id."""
    owner = {k: pid for pid, p in pieces.items() for k in piece_keys(p)}
    citing: list[tuple[str, dict]] = []
    rulebooks = rules_folder(j)          # 5_zoning_rules, or a state folder's 5_building_code_rules
    for path in rulebook_paths(rulebooks):     # every rulebook, hand-drafted or in drafted/
        tag = "drafted:" if "drafted" in path.relative_to(rulebooks).parts else ""
        citing += [(tag + r.get("id", "?"), s) for r in (load(path) or {}).get("rules", []) for s in r.get("sources", [])]
    for path in (j / "4_term_definitions" / f"{schema}.yaml" for schema in TERM_SCHEMAS):  # not the term index
        if not path.exists():
            continue
        citing +=[(f"{path.stem}.{key}", s) for key, e in (load(path) or {}).items() for s in e.get("sources", [])]
    out: dict[str, list[str]] = {}
    for who, s in citing:
        lines = s.get("lines") or []
        if s.get("file") != file or len(lines) != 2:
            continue
        for n in range(lines[0], lines[1] + 1):
            if (pid := owner.get((s.get("page"), n))) and who not in out.setdefault(pid, []):
                out[pid].append(who)
    return out


# Words that put a requirement on a design. Deliberately broad: a false alarm costs a reviewer a minute,
# a missed requirement could let a design pass that should fail.
REQUIREMENT_WORDS = re.compile(
    r"\b(shall not|shall be not|shall have|shall be located|shall conform|shall be in conformity|shall be deemed|"
    r"shall comply|shall be provided|shall meet|shall be permitted|"   # the model codes' verbs (ICC books)
    r"shall be considered|must|may not|not to exceed|exceed(?:s|ed|ing)?|(?:more|less|fewer|greater) than|"
    r"at least|at most|is required|are required|prohibited|maximum|minimum|(?<!not )limited to|"
    r"no(?:\s+[\w/-]+){1,6}\s+shall)\b", re.I)    # patterns, not instances: "No structure shall", "less than 60"


def requirement_words(rows: list[dict], piece: dict) -> list[str]:
    """The requirement words in a piece's own text, in order of first use."""
    keys = set(piece_keys(piece))
    text = " ".join(r["text"] for r in rows[1:] if (r["page"], r["line"]) in keys)
    return list(dict.fromkeys(m.group(1).lower() for m in REQUIREMENT_WORDS.finditer(text)))


def review_list(header: dict, pieces: dict[str, dict], labels: dict, cited: dict[str, list[str]],
                rows: list[dict]) -> str:
    """Markdown: the not_for_checking labels, the reference labels that use requirement words, and the
    cited pieces, with each label's reason and status."""
    def row(pid, extra=""):
        e = labels.get(pid, {})
        quote = (e.get("sources") or [{}])[0].get("quote", "")
        state = e.get("status", "not labeled yet") + (" · open questions" if e.get("open_questions") else "")
        return (f"| {pid} | {pieces[pid]['title'].replace('|', '/')} | {e.get('label', '—')} | {state} | "
                f"{e.get('reason', '').replace('|', '/')} | {quote.replace('|', '/')} |{extra}")
    head = "| Piece | Title | Label | Status | Reason | Quote |"
    nfc = [pid for pid in pieces if labels.get(pid, {}).get("label") == "not_for_checking"]
    asked = [pid for pid in pieces if labels.get(pid, {}).get("open_questions")]
    worded = {pid: words for pid in pieces if labels.get(pid, {}).get("label") == "reference"
              and (words := requirement_words(rows, pieces[pid]))}
    out = [f"# Labels to review: {header['file']}", "",
           "Generated by `python -m section_labeling coverage`. Never hand-edit.", "",
           "To record a doubt, add an `open_questions` entry to the label in "
           f"`3_section_labels/{Path(header['file']).stem}.yaml`; an architect answers it (`answers`). Approving "
           "labels, as for rules, is deferred for now; an approved label is never overwritten by a later run.", "",
           f"## Labeled not for checking ({len(nfc)})", "",
           "Never checked: a rule wrongly put here could let a design pass that should fail.", "",
           head, "|---|---|---|---|---|---|", *[row(pid) for pid in nfc], "",
           f"## Labeled reference but using requirement words ({len(worded)})", "",
           "Only rules become formulas: check each is really only a definition or pointer, not a requirement.", "",
           head + " Words |", "|---|---|---|---|---|---|---|",
           *[row(pid, f" {', '.join(worded[pid])} |") for pid in worded], "",
           f"## Open questions for the architects ({len(asked)})", "",
           "A reviewer's doubt about the label, for an architect to answer (`answers`). An answered question also unblocks approval, once approval is switched on (deferred for now).", "",
           head + " Questions |", "|---|---|---|---|---|---|---|",
           *[row(pid, f" {' / '.join(q.replace('|', '/') for q in labels[pid]['open_questions'])} |") for pid in asked], "",
           f"## Cited by rules or definitions ({len(cited)})", "",
           "A rule or definition already quotes these pieces, so each should be rule or reference.", "",
           head + " Cited by |", "|---|---|---|---|---|---|---|",
           *[row(pid, f" {', '.join(cited[pid])} |") for pid in pieces if pid in cited]]
    return "\n".join(out) + "\n"


def provenance_problems(labels: dict, records: list[dict], pieces: dict, rows: list[dict], file: str,
                        ctx) -> list[str]:
    """Every AI-drafted label must be exactly what a recorded answer produces, or say how it differs. The
    answer's sources are rebuilt with the labeler's own code (labeler.answer_sources); the label (its
    original, before any {from} revision), topic, reason (unless a {from} revision rewrote it) and sources
    (page, lines and words) must equal one accepted answer's, unless a {field: sources} revision explains
    the sources. Plain code over the run records."""
    from .labeler import answer_sources
    accepted: dict[str, list[dict]] = {}
    for r in records:
        if r.get("problem") is None and r.get("answer"):
            try:
                accepted.setdefault(r["piece"], []).append(json.loads(r["answer"]))
            except json.JSONDecodeError:
                pass
    out = []
    for pid, e in labels.items():
        if not str(e.get("drafted_by", "")).startswith("section_labeling/") or pid not in pieces:
            continue
        revised = e.get("revised") or []
        original = next((r["from"] for r in revised if "from" in r), e.get("label"))
        place = lambda s: (s.get("page"), tuple(s.get("lines") or ()), s.get("quote"))
        have = {place(s) for s in e.get("sources") or []}
        relabeled = any("from" in r for r in revised)        # a label change rewrites the reason too
        candidates = [a for a in accepted.get(pid, []) if a.get("label") == original
                      and a.get("topic") == e.get("topic")
                      and (relabeled or str(a.get("reason", "")).strip() == str(e.get("reason", "")).strip())]
        rebuilt = [{place(s) for s in srcs} for a in candidates
                   for srcs, _ in [answer_sources(a, pieces[pid], rows, file, ctx)] if srcs]
        if not rebuilt:
            out.append(f"{pid}: no recorded answer has label {original!r} with this topic and reason")
        elif have not in rebuilt:
            if not any(r.get("field") == "sources" for r in revised):
                out.append(f"{pid}: sources differ from what its recorded answer produces, with no sources revision")
            elif not any(s <= have for s in rebuilt):
                out.append(f"{pid}: a sources revision must keep what the recorded answer produced")
    return out
