"""The coverage report and the review list.

The coverage report: proof that every line of a law was read, and what was decided about it.

Recomputed from the extracted text itself (not from the splitter's own bookkeeping): every line of the
document must belong to exactly one piece, or be page furniture. A line in no piece, or in two, is a
failure. Each piece is then shown with its label (or "unlabeled") and whether an architect approved it.
Plain code; the report is generated, never hand-edited.

The review list: the labels a person must look at first. Every piece labeled not_for_checking (it is
never checked, so a rule wrongly put there could let a design pass that should fail), and every piece a
rule or definition already cites (if its label is wrong, a rule rests on a misread piece). And, found by
plain code whatever the AI said, every piece labeled reference that uses requirement words ("shall not",
"must", "not less than"...): only rules become formulas, so a requirement filed as reference could be missed. A reviewer
records a doubt as an open question on the label; an architect answers it and approves the label, the
same way as for rules.
"""

import re
from collections import Counter
from pathlib import Path

from document_extraction.sections import piece_keys
from rule_format.labels import LABEL_KINDS
from rule_format.rulebook import load


def line_problems(rows: list[dict], header: dict, pieces: dict[str, dict]) -> list[str]:
    """Lines of the extracted text not owned by exactly one piece (furniture counts as owned), plus the
    splitter's own problems (sections in the table of contents that weren't found, or the reverse)."""
    owners = Counter(k for p in pieces.values() for k in piece_keys(p))
    owners.update(tuple(k) for k in header["furniture"])
    lines = [(r["page"], r["line"]) for r in rows[1:]]
    in_text = set(lines)
    problems = [f"p.{p} line {n}: in no piece" for p, n in lines if owners[(p, n)] == 0]
    problems += [f"p.{p} line {n}: in {owners[(p, n)]} pieces" for p, n in lines if owners[(p, n)] > 1]
    problems += [f"p.{p} line {n}: a piece claims a line that isn't in the text" for p, n in owners if (p, n) not in in_text]
    return problems + list(header.get("problems", ["the sections file has no 'problems' list; re-run python -m document_extraction"]))


def report(rows: list[dict], header: dict, pieces: dict[str, dict], labels: dict) -> str:
    """The Markdown report for one document."""
    problems = line_problems(rows, header, pieces)
    counts = Counter(labels.get(i, {}).get("label", "unlabeled") for i in pieces)
    approved = sum(labels.get(i, {}).get("status") == "approved" for i in pieces)
    out = [f"# Coverage: {header['file']}", "",
           "Generated by `python -m section_labeling coverage`. Never hand-edit.", "",
           f"- **Lines of text:** {len(rows) - 1} ({len(header['furniture'])} are page furniture: the repeated page "
           "title, running header and download footer)",
           f"- **Pieces:** {len(pieces)}, cut at the law's own headings",
           f"- **Lines in no piece or in two, or sections missing from the table of contents:** {len(problems)}"
           + (" ✓" if not problems else " ✗"),
           f"- **Labels:** " + ", ".join(f"{k} {counts[k]}" for k in (*LABEL_KINDS, "unlabeled")),
           f"- **Approved by an architect:** {approved} of {len(pieces)}", ""]
    out += [f"- ✗ {p}" for p in problems[:50]] + ([""] if problems else [])
    out += ["| Piece | Title | Pages | Label | Status |", "|---|---|---|---|---|"]
    for pid, p in pieces.items():
        pages = sorted({pg for pg, _, _ in p["lines"]})
        where = str(pages[0]) if len(pages) == 1 else f"{pages[0]}–{pages[-1]}"
        entry = labels.get(pid, {})
        title = p["title"].replace("|", "/")
        out.append(f"| {pid} | {title} | {where} | {entry.get('label', 'unlabeled')} | {entry.get('status', '')} |")
    return "\n".join(out) + "\n"


def cited_by(j: Path, file: str, pieces: dict[str, dict]) -> dict[str, list[str]]:
    """{piece id: [rule or definition ids citing it]}, from every source in the rulebook (5_zoning_rules)
    and the definitions and uses (4_term_definitions) that quotes this document."""
    owner = {k: pid for pid, p in pieces.items() for k in piece_keys(p)}
    citing: list[tuple[str, dict]] = []
    rulebooks = j / "5_zoning_rules"          # the hand drafts and the script's drafted/ (not its records/)
    for path in sorted(p for p in rulebooks.rglob("*.yaml") if "records" not in p.relative_to(rulebooks).parts):
        citing += [(r.get("id", "?"), s) for r in (load(path) or {}).get("rules", []) for s in r.get("sources", [])]
    for path in sorted((j / "4_term_definitions").glob("*.yaml")):
        citing += [(f"{path.stem}.{key}", s) for key, e in (load(path) or {}).items() for s in e.get("sources", [])]
    out: dict[str, list[str]] = {}
    for who, s in citing:
        lines = s.get("lines") or []
        if s.get("file") != file or len(lines) != 2:
            continue
        for n in range(lines[0], lines[1] + 1):
            if (pid := owner.get((s.get("page"), n))) and who not in out.setdefault(pid, []):
                out[pid].append(who)
    return out


# Words that put a requirement on a design. Deliberately broad: a false alarm costs a reviewer a minute,
# a missed requirement could let a design pass that should fail.
REQUIREMENT_WORDS = re.compile(r"\b(shall not|shall be not|shall have|shall be located|shall conform|"
                               r"shall be in conformity|shall be deemed|shall be considered|must|may not|"
                               r"not less than|not more than|no more than|no less than|not to exceed|exceeds?|"
                               r"at least|at most|is required|are required|prohibited|maximum|minimum|"
                               r"no(?:\s+[\w-]+){1,3}\s+shall)\b", re.I)    # "No structure shall ..."


def requirement_words(rows: list[dict], piece: dict) -> list[str]:
    """The requirement words in a piece's own text, in order of first use."""
    keys = set(piece_keys(piece))
    text = " ".join(r["text"] for r in rows[1:] if (r["page"], r["line"]) in keys)
    return list(dict.fromkeys(m.group(1).lower() for m in REQUIREMENT_WORDS.finditer(text)))


def review_list(header: dict, pieces: dict[str, dict], labels: dict, cited: dict[str, list[str]],
                rows: list[dict]) -> str:
    """Markdown: the not_for_checking labels, the reference labels that use requirement words, and the
    cited pieces, with each label's reason and status."""
    def row(pid, extra=""):
        e = labels.get(pid, {})
        quote = (e.get("sources") or [{}])[0].get("quote", "")
        state = e.get("status", "not labeled yet") + (" · open questions" if e.get("open_questions") else "")
        return (f"| {pid} | {pieces[pid]['title'].replace('|', '/')} | {e.get('label', '—')} | {state} | "
                f"{e.get('reason', '').replace('|', '/')} | {quote.replace('|', '/')} |{extra}")
    head = "| Piece | Title | Label | Status | Reason | Quote |"
    nfc = [pid for pid in pieces if labels.get(pid, {}).get("label") == "not_for_checking"]
    worded = {pid: words for pid in pieces if labels.get(pid, {}).get("label") == "reference"
              and (words := requirement_words(rows, pieces[pid]))}
    out = [f"# Labels to review: {header['file']}", "",
           "Generated by `python -m section_labeling coverage`. Never hand-edit.", "",
           "To record a doubt, add an `open_questions` entry to the label in "
           f"`3_section_labels/{Path(header['file']).stem}.yaml`; an architect answers it (`answers`) and approves "
           "the label, as for rules. An approved label is never overwritten by a later run.", "",
           f"## Labeled not for checking ({len(nfc)})", "",
           "Never checked: a rule wrongly put here could let a design pass that should fail.", "",
           head, "|---|---|---|---|---|---|", *[row(pid) for pid in nfc], "",
           f"## Labeled reference but using requirement words ({len(worded)})", "",
           "Only rules become formulas: check each is really only a definition or pointer, not a requirement.", "",
           head + " Words |", "|---|---|---|---|---|---|---|",
           *[row(pid, f" {', '.join(worded[pid])} |") for pid in worded], "",
           f"## Cited by rules or definitions ({len(cited)})", "",
           "A rule or definition already quotes these pieces, so each should be rule or reference.", "",
           head + " Cited by |", "|---|---|---|---|---|---|---|",
           *[row(pid, f" {', '.join(cited[pid])} |") for pid in pieces if pid in cited]]
    return "\n".join(out) + "\n"
