"""The term index: for every defined term (and the words that mean the same thing), every piece of the law that
uses it. Like the index at the back of a book, so whoever drafts or reviews a rule reads every related section,
not just the definition: the "yard" entry lists §325-18B, the rule on eaves projecting into a yard.

Plain code, no AI. Inputs: the definitions (4_term_definitions/definitions.yaml), the synonyms
(regulations/document_extraction_guide/term_synonyms.yaml) and the law cut into pieces. Output:
4_term_definitions/term_index.yaml, written (or checked) by `python -m section_labeling coverage`.
"""

import re

import yaml

from rule_format.rulebook import REPO

from .labeler import numbered_lines

SYNONYMS_FILE = REPO / "regulations/document_extraction_guide/term_synonyms.yaml"
INDEX_NAME = "term_index.yaml"


def entries(definitions: dict, synonyms: dict) -> dict[str, dict]:
    """{key: {title, forms}}: every definition and every concept in the synonyms file, in that file's order.
    A definition without synonyms, or a concept without a title, is an error: nothing is skipped silently."""
    missing = [k for k in definitions if k not in synonyms]
    if missing:
        raise ValueError(f"definitions with no entry in {SYNONYMS_FILE.name}: {', '.join(missing)}")
    out = {}
    for key, s in synonyms.items():
        if key in definitions:
            title = definitions[key]["term"]
        elif s.get("title"):
            title = s["title"]
        else:
            raise ValueError(f"{SYNONYMS_FILE.name}: {key!r} isn't a definition, so it needs a title")
        forms = [f.strip().lower() for f in s.get("forms") or [] if f.strip()]
        if not forms:
            raise ValueError(f"{SYNONYMS_FILE.name}: {key!r} has no forms")
        out[key] = {"title": title, "forms": list(dict.fromkeys(forms))}
    return out


def pattern(forms: list[str]) -> re.Pattern:
    """Any of the forms as whole words, any case, across line breaks and hyphens; a plain +s/+es plural too."""
    alts = sorted(({r"[\s\-]+".join(re.escape(w) for w in f.split()) for f in forms}), key=len, reverse=True)
    return re.compile(r"(?<![\w-])(?:" + "|".join(alts) + r")(?:s|es)?(?![\w-])", re.IGNORECASE)


def mentions(lines: list[tuple[int, int, str]], rx: re.Pattern) -> list[list[int]]:
    """[[page, line], ...] where a match starts, matching across line breaks."""
    text, starts = "", []
    for page, line, t in lines:
        starts.append((len(text), page, line))
        text += t + " "
    found = []
    for m in rx.finditer(text):
        page, line = next((p, ln) for off, p, ln in reversed(starts) if off <= m.start())
        if [page, line] not in found:
            found.append([page, line])
    return found


def build(definitions: dict, synonyms: dict, laws: list[tuple[str, dict, list[dict]]]) -> dict:
    """The index over every law cut into pieces ([(document, pieces, rows)]): {documents, terms: {key: {title,
    forms, pieces: [{piece, title, at: [[page, line], ...]}]}}}, pieces in each law's own order. With more than
    one document, each piece also names its document."""
    many = len(laws) > 1
    texts = [(doc, pid, piece, numbered_lines(rows, piece)) for doc, pieces, rows in laws for pid, piece in pieces.items()]
    terms = {}
    for key, e in entries(definitions, synonyms).items():
        rx = pattern(e["forms"])
        found = [({"document": doc} if many else {}) | {"piece": pid, "title": piece["title"], "at": at}
                 for doc, pid, piece, lines in texts if (at := mentions(lines, rx))]
        terms[key] = {"title": e["title"], "forms": e["forms"], "pieces": found}
    return {"documents": [doc for doc, _, _ in laws], "terms": terms}


def render(index: dict) -> str:
    head = ("# Generated by `python -m section_labeling coverage` (plain code, no AI); never edit by hand.\n"
            "# For every defined term and its synonyms (regulations/document_extraction_guide/term_synonyms.yaml),\n"
            "# every piece of the law that uses it, with the [page, line] of each use.\n")
    def flow(value) -> str:                       # one line, so each section is one row of the file
        return yaml.safe_dump(value, default_flow_style=True, allow_unicode=True, width=10_000, sort_keys=False).strip()
    out = [head + f"documents: {flow(index['documents'])}", "terms:"]
    for key, e in index["terms"].items():
        out += [f"  {key}:", f"    title: {flow(e['title'])}", f"    forms: {flow(e['forms'])}",
                "    pieces:" + ("" if e["pieces"] else " []")]
        out += [f"    - {flow(p)}" for p in e["pieces"]]
    return "\n".join(out) + "\n"


def related(index: dict, text: str) -> list[str]:
    """Piece ids the index lists for every term the text uses, in the order the terms are listed, deduplicated."""
    out = []
    for e in index["terms"].values():
        if pattern(e["forms"]).search(text):
            out += [p["piece"] for p in e["pieces"] if p["piece"] not in out]
    return out
