"""Measure a Rhino model, or check the committed measured projects are current.

    python -m model_measurement <model.3dm> <facts.yaml>   # prints each measurement; writes <model>_measured.yaml
    python -m model_measurement --check                    # CI: every committed measured project matches a fresh one

A measured project sits next to its model and its facts file (`<model>_facts.yaml`), and is a project file the
compliance report reads (python -m project_report).
"""

import argparse
import sys
from pathlib import Path

import yaml

from rule_format.rulebook import REPO, load

from .project import load_facts, project

HEADER = ("# Generated by python -m model_measurement from {model} and {facts}. Do not edit:\n"
          "# re-run it. Every value is measured from the model or stated in the lot facts; `from` says which.\n")


def pairs() -> list[tuple[Path, Path, Path]]:
    """(model, facts, measured project) for every committed facts file under test_data/test_sites/."""
    found = []
    for facts in sorted((REPO / "test_data/test_sites").rglob("*_facts.yaml")):
        model = facts.with_name(facts.name.removesuffix("_facts.yaml") + ".3dm")
        found.append((model, facts, facts.with_name(facts.name.removesuffix("_facts.yaml") + "_measured.yaml")))
    return found


def text(model: Path, facts_path: Path) -> str:
    data = project(model, load_facts(facts_path))
    return HEADER.format(model=model.name, facts=facts_path.name) + yaml.safe_dump(
        data, sort_keys=False, allow_unicode=True, width=1000)


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(prog="python -m model_measurement")
    parser.add_argument("model", nargs="?", type=Path)
    parser.add_argument("facts", nargs="?", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    if args.check:
        failed = 0
        for model, facts, out in pairs():
            same = out.exists() and out.read_text() == text(model, facts)
            print(f"{'✓' if same else '✗'} {out.relative_to(REPO)}{'' if same else ': differs from a fresh measurement'}")
            failed += not same
        return 1 if failed else 0
    if not (args.model and args.facts):
        parser.error("give a model and its facts file, or --check")
    try:
        out_text = text(args.model, args.facts)
    except ValueError as e:
        print(f"✗ {e}")
        return 1
    for name, m in yaml.safe_load(out_text)["measurements"].items():
        print(f"{name:18} {str(m['value']):>14}  {m['from']}")
    out = args.model.with_name(args.model.stem + "_measured.yaml")
    out.write_text(out_text)
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
